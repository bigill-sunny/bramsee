import assert from 'node:assert/strict';
import {departureTime} from '../lib/departure.ts';
import {loadServiceTrips,plan} from '../lib/planner.ts';
assert.equal(new Date(departureTime('2026-10-17T09:00')).toISOString(),'2026-10-17T13:00:00.000Z');
assert.equal(new Date(departureTime('2026-12-17T09:00')).toISOString(),'2026-12-17T14:00:00.000Z');
assert.ok(Number.isNaN(departureTime('2027-03-14T02:30')),'Nonexistent DST time is rejected');
assert.ok(Number.isNaN(departureTime('2026-02-30T10:00')));
assert.ok(Number.isNaN(departureTime('nonsense')));
const from={id:'A',code:'1',name:'Start',lat:43.7,lon:-79.8},to={id:'B',code:'2',name:'End',lat:43.75,lon:-79.8};
const catalog={stops:[from,to],routes:{'1':{id:'1',number:'1',name:'Test'}},calendar:{20261017:['tomorrow']},validUntil:'20261018'};
const trip={id:'test',route:'1',headsign:'North',service:'tomorrow',stops:[['A',9*3600+600,1,0,0],['B',9*3600+1200,2,0,0]]};
const at=departureTime('2026-10-17T09:00'),loaded=[];
const trips=await loadServiceTrips(catalog,async id=>{loaded.push(id);return [trip]},at);
assert.deepEqual(loaded,['tomorrow']);
const options=plan(from,to,catalog,trips,null,400,at);
assert.ok(options.length,'Future departure uses the selected service date');
assert.equal(options[0].legs[0].departure,Date.parse('2026-10-17T13:10:00Z')/1000);
assert.equal(options[0].legs[0].live,false);
console.log('Departure tests passed: Toronto timezone, winter offset, DST rejection and future service routing.');

import assert from 'node:assert/strict';
import {positionFix,locationStatus,watchLocation} from '../lib/location.ts';
const now=Date.now();
const point=(lat=43.7,lon=-79.85)=>({coords:{latitude:lat,longitude:lon,accuracy:12},timestamp:now});
assert.deepEqual(positionFix(point()),{lat:43.7,lon:-79.85,accuracy:12,updated:now});
assert.throws(()=>positionFix(point(NaN)));
assert.throws(()=>positionFix(point(100)));
assert.equal(locationStatus(null,true,now).label,'Waiting for your location');
assert.equal(locationStatus(positionFix(point()),true,now).fresh,true);
assert.equal(locationStatus(positionFix(point()),true,now+31000).fresh,false);
assert.equal(locationStatus(positionFix(point()),false,now).fresh,false);
let success,error,options,cleared=[],fixes=[],errors=[];
const geo={watchPosition:(s,e,o)=>{success=s;error=e;options=o;return 7},clearWatch:id=>cleared.push(id)};
const stop=watchLocation(geo,p=>fixes.push(p),(message,denied)=>errors.push({message,denied}));
assert.equal(options.enableHighAccuracy,true);assert.equal(options.maximumAge,5000);
success(point());success(point(43.701));assert.equal(fixes.length,2,'Continuous fixes reach the moving marker');
error({code:3});assert.equal(errors.at(-1).denied,false);assert.match(errors.at(-1).message,/paused/);
error({code:1});assert.equal(errors.at(-1).denied,true);
success(point(NaN));assert.match(errors.at(-1).message,/invalid/);
stop();stop();assert.deepEqual(cleared,[7],'Stop and unmount clear the watch exactly once');
success(point());error({code:1});assert.equal(fixes.length,2,'Late callbacks cannot restart tracking');assert.equal(errors.length,3);
const blocked=[];const closeBlocked=watchLocation({watchPosition(){throw Error('blocked')},clearWatch(){assert.fail('No watch exists')}},()=>assert.fail('No fix expected'),(message,denied)=>blocked.push({message,denied}));
assert.equal(blocked[0].denied,true);closeBlocked();
console.log('GPS checks passed: continuous updates, accuracy, freshness, permission/timeout errors, invalid fixes and cleanup. No real location was requested.');

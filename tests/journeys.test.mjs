import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {parseJourneys,rankJourneys,direction,routeNumber,applyWalkingTimes} from '../lib/journeys.ts';
import {namespaceGO,mergeAgencyFeeds} from '../lib/go-realtime.ts';
import {loadServiceTrips,plan} from '../lib/planner.ts';
import {departureTime} from '../lib/departure.ts';
const point={name:'Test stop',lat:43.7,lon:-79.8};
const saved={id:'test',name:'University',from:point,to:{...point,name:'Destination'}};
assert.deepEqual(parseJourneys(JSON.stringify([saved])),[saved]);
for(const raw of ['broken','{}','null',JSON.stringify([{...saved,from:{...point,lat:'43'}}]),JSON.stringify([{...saved,name:' '}])])assert.deepEqual(parseJourneys(raw),[]);
const now=Date.parse('2026-10-16T08:00:00-04:00'),seconds=now/1000;
const options=[{id:'slow',arrival:seconds+1800},{id:'fast',arrival:seconds+600}];
assert.deepEqual(rankJourneys(options,{duration:900},now,40).map(x=>x.id),['fast','walking','slow']);
assert.deepEqual(rankJourneys(options,null,now,30).map(x=>x.id),['walking','fast','slow']);
assert.deepEqual(rankJourneys([{id:'transfer',arrival:seconds+610},{id:'direct',arrival:seconds+620}],{duration:700},now,40).map(x=>x.id),['transfer','direct','walking'],'Strict arrival order, even when options are less than 30 seconds apart');
const adjusted=applyWalkingTimes({id:'checked',legs:[{arrival:seconds+500}],arrival:seconds+600},[{duration:200},{duration:300}],now);
assert.equal(adjusted.arrival,seconds+800,'Final pedestrian path is included in destination arrival');
assert.equal(adjusted.walk,500/60);
const go=namespaceGO({timestamp:seconds,items:[{trip:'123',timestamp:0,stops:[{id:'UN'}]}]},'trips');
assert.equal(go.items[0].trip,'GO:123');assert.equal(go.items[0].stops[0].id,'GO:UN');assert.equal(go.items[0].timestamp,seconds);
const merged=mergeAgencyFeeds([{timestamp:seconds-180,items:[{trip:'stale'}]},go],'trips',now);
assert.deepEqual(merged.items.map(i=>i.trip),['GO:123'],'Fresh agency data cannot revive another agency’s stale predictions');
assert.throws(()=>mergeAgencyFeeds([{timestamp:seconds-180,items:[]}],'trips',now));
const catalog=JSON.parse(await readFile(new URL('../public/data/catalog.json',import.meta.url),'utf8'));
const date=Object.keys(catalog.calendar).sort().find(d=>(catalog.calendar[d].some(k=>k.startsWith('GO-')))&&![0,6].includes(new Date(d.slice(0,4)+'-'+d.slice(4,6)+'-'+d.slice(6,8)+'T12:00:00Z').getUTCDay()));
assert.ok(date,'GO has a weekday in the published service calendar');
const sampleNow=departureTime(date.slice(0,4)+'-'+date.slice(4,6)+'-'+date.slice(6,8)+'T08:00');
const trips=await loadServiceTrips(catalog,async id=>JSON.parse(await readFile(new URL('../public/data/'+id+'.json',import.meta.url),'utf8')),sampleNow);
assert.ok(trips.some(t=>t.agency==='GO'&&t.mode==='train'));
assert.ok(trips.some(t=>t.agency==='GO'&&t.mode==='bus'));
const bramalea=catalog.stops.find(s=>s.id.startsWith('GO:')&&s.name==='Bramalea GO');
const union=catalog.stops.find(s=>s.id.startsWith('GO:')&&s.name==='Union Station GO');
assert.ok(bramalea&&union,'GO rail station endpoints imported');
const start=performance.now(),journeys=plan(bramalea,union,catalog,trips,null,500,sampleNow);
assert.ok(journeys.some(o=>o.legs.some(l=>l.trip.agency==='GO'&&l.trip.mode==='train')),'A real GO rail itinerary can be planned');
assert.ok(journeys.every(o=>o.legs.every(l=>!l.live)),'Scheduled GO trips are never presented as live');
const leg=journeys.find(o=>o.legs.some(l=>l.trip.agency==='GO')).legs.find(l=>l.trip.agency==='GO');
assert.match(routeNumber(leg),/^GO /);assert.ok(direction(leg));
const destinationStop=leg.trip.stops.find(s=>s[0]===leg.to.id);
assert.equal(leg.arrival,leg.trip.serviceMidnight+destinationStop[5],'GO alighting uses arrival, rather than departure after station dwell');
console.log(JSON.stringify({goJourneys:journeys.length,routingMs:Math.round(performance.now()-start),goCoverage:catalog.goCoverage}));
console.log('Journey checks passed: saved route validation, strict combined ordering, GO bus/train loading and a real GO train itinerary.');
